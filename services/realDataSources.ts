// Генерація реалістичних часових міток
export const generateRealTimestamp = (minutesAgo: number = 0) => {
    const now = new Date();
    now.setMinutes(now.getMinutes() - minutesAgo);
    return now.toISOString();
};

// Генерація реалістичних IP адрес
export const generateRealIP = () => {
    const ranges = [
        '10.0.', '192.168.', '172.16.', '185.', '88.', '45.'
    ];
    const range = ranges[Math.floor(Math.random() * ranges.length)];
    return `${range}${Math.floor(Math.random() * 255)}.${Math.floor(Math.random() * 255)}`;
};

// Генерація реалістичних ID
export const generateRealId = (prefix: string) => {
    const timestamp = Date.now().toString(36);
    const random = Math.random().toString(36).substring(2, 7);
    return `${prefix}-${timestamp}-${random}`;
};

